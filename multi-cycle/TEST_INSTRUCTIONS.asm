.text

main:
    # -------------------------------------------------------------------------
    # 1. Initialization & Arithmetic
    # -------------------------------------------------------------------------
    addi    x10, x0, 0       # x10 = 0

    addi    x11, x0, 10      # x11 = 10
    addi    x12, x0, 20      # x12 = 20
    add     x13, x11, x12    # x13 = 30
    sub     x14, x13, x11    # x14 = 20

    # -------------------------------------------------------------------------
    # 2. Comparison & Logical
    # -------------------------------------------------------------------------
    addi    x16, x0, -1      # x16 = -1
    slt     x17, x16, x11    # x17 = 1 (True: -1 < 10)
    slti    x18, x11, 0      # x18 = 0 (False: 10 > 0)

    andi    x19, x16, 1      # x19 = 1
    ori     x20, x0, 2       # x20 = 2
    and     x21, x19, x20    # x21 = 0
    or      x22, x19, x20    # x22 = 3

    # -------------------------------------------------------------------------
    # 3. Memory
    # -------------------------------------------------------------------------
    sw      x22, -4(sp)
    lw      x23, -4(sp)      # x23 = 3

    # -------------------------------------------------------------------------
    # 4. Branch
    # -------------------------------------------------------------------------
    addi    x26, x0, 5       # Loop counter = x26 = 5

loop:
    addi    x26, x26, -1     # Decrement counter
    beq     x26, x0, loop_done
    beq     x0, x0, loop

# -------------------------------------------------------------------------
# 6. Result Verification
# -------------------------------------------------------------------------
loop_done:
    addi    x10, x0, 777     # x10 = 777

end_halt:
    beq     x0, x0, end_halt
